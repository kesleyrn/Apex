"use server";

import { revalidatePath } from "next/cache";
import { getAdmin } from "@/lib/auth";
import { friendlyDbError } from "@/lib/errors";
import { BUCKET } from "@/lib/storage-shared";
import { createClient } from "@/lib/supabase/server";
import { slugify } from "@/lib/utils";
import { productPayloadSchema } from "@/lib/validations/product";
import type { ActionResult, ProductStatus } from "@/types";
import { z } from "zod";

const idSchema = z.string().uuid();
const fail = (error: string): ActionResult => ({ ok: false, error });
const refresh = () => revalidatePath("/", "layout");

async function uniqueSlug(base: string, existing: (prefix: string) => Promise<string[]>) {
  const taken = new Set(await existing(base));
  if (!taken.has(base)) return base;
  for (let i = 2; i < 500; i++) if (!taken.has(`${base}-${i}`)) return `${base}-${i}`;
  return `${base}-${Date.now()}`;
}

export async function createProduct(id: string, input: unknown): Promise<ActionResult> {
  if (!(await getAdmin())) return fail("Please sign in again.");
  const parsedId = idSchema.safeParse(id);
  const parsed = productPayloadSchema.safeParse(input);
  if (!parsedId.success || !parsed.success) return fail(parsed.success ? "Invalid product." : parsed.error.issues[0]?.message ?? "Check the form.");
  const p = parsed.data;

  const supabase = await createClient();
  const slug = await uniqueSlug(slugify(p.name) || "product", async (prefix) => {
    const { data } = await supabase.from("products").select("slug").like("slug", `${prefix}%`);
    return (data ?? []).map((r) => r.slug);
  });

  const { error } = await supabase.from("products").insert({
    id: parsedId.data,
    slug,
    name: p.name,
    product_code: p.product_code ? p.product_code.toUpperCase() : undefined, // blank = auto-generated by the database
    category_id: p.category_id,
    description: p.description,
    price: p.price,
    availability: p.availability,
    status: p.status,
    is_featured: p.is_featured,
    sizes: p.sizes,
    colors: p.colors,
    image_url: p.image_url,
    gallery: p.gallery,
  });
  if (error) return fail(friendlyDbError(error));
  refresh();
  return { ok: true };
}

export async function updateProduct(id: string, input: unknown): Promise<ActionResult> {
  if (!(await getAdmin())) return fail("Please sign in again.");
  const parsedId = idSchema.safeParse(id);
  const parsed = productPayloadSchema.safeParse(input);
  if (!parsedId.success || !parsed.success) return fail(parsed.success ? "Invalid product." : parsed.error.issues[0]?.message ?? "Check the form.");
  const p = parsed.data;

  const supabase = await createClient();
  const { data, error } = await supabase
    .from("products")
    .update({
      name: p.name,
      ...(p.product_code ? { product_code: p.product_code.toUpperCase() } : {}),
      category_id: p.category_id,
      description: p.description,
      price: p.price,
      availability: p.availability,
      status: p.status,
      is_featured: p.is_featured,
      sizes: p.sizes,
      colors: p.colors,
      image_url: p.image_url,
      gallery: p.gallery,
    })
    .eq("id", parsedId.data)
    .select("id");
  if (error) return fail(friendlyDbError(error));
  if (!data || data.length === 0) return fail("Product not found, or you do not have permission to edit it.");
  refresh();
  return { ok: true };
}

export async function setProductStatus(id: string, status: ProductStatus): Promise<ActionResult> {
  if (!(await getAdmin())) return fail("Please sign in again.");
  if (!idSchema.safeParse(id).success || !["draft", "published"].includes(status)) return fail("Invalid request.");
  const supabase = await createClient();
  const { data, error } = await supabase.from("products").update({ status }).eq("id", id).select("id");
  if (error) return fail(friendlyDbError(error));
  if (!data || data.length === 0) return fail("Product not found.");
  refresh();
  return { ok: true };
}

export async function deleteProduct(id: string): Promise<ActionResult> {
  if (!(await getAdmin())) return fail("Please sign in again.");
  if (!idSchema.safeParse(id).success) return fail("Invalid request.");
  const supabase = await createClient();
  const { data, error } = await supabase.from("products").delete().eq("id", id).select("id");
  if (error) return fail(friendlyDbError(error));
  if (!data || data.length === 0) return fail("Product not found.");

  // Remove every image stored for this product.
  const folder = `products/${id}`;
  const { data: files } = await supabase.storage.from(BUCKET).list(folder);
  if (files && files.length > 0) await supabase.storage.from(BUCKET).remove(files.map((f) => `${folder}/${f.name}`));
  refresh();
  return { ok: true };
}
